"""Render Delta DDL from the table contracts (Ticket 2).

Unity Catalog accepts informational PRIMARY KEY / FOREIGN KEY constraints (never
enforced); ``unity_catalog=False`` drops them so the same DDL runs on local OSS Delta
for tests. Referential integrity is enforced by ``banking_dwh.dq.checks`` instead.

    python -m banking_dwh.contracts.ddl --target prod > ddl/02_star_schema.sql
"""

from __future__ import annotations

import argparse
from typing import Iterable

from ..common.config import EnvConfig
from .tables import BRONZE_TABLES, OPS_TABLES, SILVER_TABLES, TableContract

DEFAULT_PROPERTIES = {
    "delta.enableChangeDataFeed": "true",
    "delta.autoOptimize.optimizeWrite": "true",
}


def _q(text: str) -> str:
    return text.replace("\\", "\\\\").replace("'", "\\'")


def create_table_sql(cfg: EnvConfig, t: TableContract, *, unity_catalog: bool = True) -> str:
    lines = []
    for c in t.columns:
        col = f"  {c.name} {c.type}{'' if c.nullable else ' NOT NULL'}"
        if c.comment:
            col += f" COMMENT '{_q(c.comment)}'"
        lines.append(col)
    if unity_catalog and t.primary_key:
        lines.append(f"  CONSTRAINT pk_{t.name} PRIMARY KEY ({', '.join(t.primary_key)})")
    if unity_catalog:
        for fk in t.foreign_keys:
            ref = cfg.table(t.layer, fk.ref_table)
            lines.append(
                f"  CONSTRAINT {fk.name} FOREIGN KEY ({', '.join(fk.columns)}) "
                f"REFERENCES {ref} ({', '.join(fk.ref_columns)})"
            )
    sql = f"CREATE TABLE IF NOT EXISTS {cfg.table(t.layer, t.name)} (\n" + ",\n".join(lines) + "\n)\nUSING DELTA"
    if unity_catalog and t.cluster_by:
        sql += f"\nCLUSTER BY ({', '.join(t.cluster_by)})"
    sql += f"\nCOMMENT '{_q(t.comment)}'"
    props = {**DEFAULT_PROPERTIES, **t.properties, "banking_dwh.layer": t.layer}
    if t.legacy_name:
        props["banking_dwh.legacy_table"] = f"DWH.dbo.{t.legacy_name}"
    if t.owner_ticket:
        props["banking_dwh.owner_ticket"] = str(t.owner_ticket)
    sql += "\nTBLPROPERTIES (\n" + ",\n".join(f"  '{k}' = '{_q(v)}'" for k, v in props.items()) + "\n)"
    return sql


def star_schema_statements(cfg: EnvConfig, *, unity_catalog: bool = True) -> list[str]:
    return [create_table_sql(cfg, t, unity_catalog=unity_catalog) for t in (*SILVER_TABLES, *OPS_TABLES)]


def bronze_statements(cfg: EnvConfig, *, unity_catalog: bool = True) -> list[str]:
    """Optional: pre-create Bronze tables (ingestion tickets may also create them on first write)."""
    return [create_table_sql(cfg, t, unity_catalog=unity_catalog) for t in BRONZE_TABLES]


def render_script(statements: Iterable[str], header: str) -> str:
    body = ";\n\n".join(statements)
    return f"{header}\n\n{body};\n"


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--target", default="prod")
    p.add_argument("--what", choices=["star_schema", "bronze"], default="star_schema")
    a = p.parse_args(argv)
    cfg = EnvConfig.from_target(a.target)
    stmts = star_schema_statements(cfg) if a.what == "star_schema" else bronze_statements(cfg)
    header = (
        f"-- GENERATED by `python -m banking_dwh.contracts.ddl --target {a.target} --what {a.what}`;"
        " do not edit by hand.\n-- Source of truth: databricks/src/banking_dwh/contracts/tables.py"
    )
    print(render_script(stmts, header), end="")


if __name__ == "__main__":
    main()
